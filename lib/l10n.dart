import 'package:flutter/foundation.dart';

/// Minimal i18n: one dictionary, two locales, resolved at startup from
/// settings. Upgrade path to flutter gen-l10n if the app grows past MVP.

class L10n {
  static final ValueNotifier<int> notifier = ValueNotifier<int>(0);

  static String setting = 'system'; // 'system' | 'en' | 'zh'
  static String _resolved = 'en';

  static void setLang(String setting, {String systemLocale = 'en'}) {
    L10n.setting = setting;
    _resolved = switch (setting) {
      'en' => 'en',
      'zh' => 'zh',
      _ => systemLocale.startsWith('zh') ? 'zh' : 'en',
    };
    notifier.value++;
  }

  static bool get zh => _resolved == 'zh';

  static String t(String key) => (_dict[_resolved] ?? _dict['en']!)[key] ?? key;

  /// t() with a {n} placeholder filled in.
  static String tf(String key, Object n) => t(key).replaceAll('{n}', '$n');

  static String muscle(String key) =>
      (_muscles[_resolved] ?? _muscles['en']!)[key] ?? key;
}

